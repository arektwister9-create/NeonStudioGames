const fs=require('node:fs');const path=require('node:path');const babel=require('@babel/core');
const root=path.resolve(__dirname,'../app/src/main/assets'),out=path.join(root,'compat');fs.mkdirSync(out,{recursive:true});
for(const file of fs.readdirSync(root).filter(n=>n.endsWith('.js'))){
 const result=babel.transformSync(fs.readFileSync(path.join(root,file),'utf8'),{filename:file,sourceType:'script',comments:true,compact:false,presets:[[require.resolve('@babel/preset-env'),{targets:{chrome:'44'},modules:false,useBuiltIns:false}]]});
 const body=file==='legacy-support.js'?result.code:'if (!window.NeonUnsupportedWebView) {\n'+result.code+'\n}';
 fs.writeFileSync(path.join(out,file),'// Generated by npm run build:runtime. Edit ../'+file+' instead.\n'+body+'\n');
}
console.log('Generated offline WebView-compatible runtime scripts');
